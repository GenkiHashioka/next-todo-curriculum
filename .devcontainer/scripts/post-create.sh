#!/usr/bin/env bash
#
# Dev Container の初回作成時に一度だけ実行されるセットアップスクリプト。
#
# ここでやることは「受講者が手で打つと間違えやすい／忘れやすい」ものに絞っている。
# 環境構築はカリキュラム最初の離脱ポイントなので、自動化できる分は自動化する。
set -euo pipefail

WORKSPACE="${WORKSPACE_DIR:-/workspace}"
cd "${WORKSPACE}"

# マウントされたリポジトリはホスト側の所有者のままなので、git が
# 「dubious ownership」として操作を拒否する。以降の git 操作より先に許可しておく。
git config --global --add safe.directory "${WORKSPACE}"

GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

log()  { echo -e "${GREEN}[setup]${NC} $*"; }
warn() { echo -e "${YELLOW}[setup]${NC} $*"; }

# -----------------------------------------------------------------------------
# 1. .env を用意する
#
# JWT_SECRET はランダムな文字列であればよいので、ここで自動生成する。
# （手で `openssl rand` を打たせると、忘れる・短すぎる値を入れる等で詰まりやすい）
# -----------------------------------------------------------------------------
if [[ -f .env ]]; then
  log ".env は既にあるのでそのまま使います"
else
  cp .env.example .env
  secret="$(openssl rand -base64 48 | tr -d '\n')"
  # 区切り文字に | を使う。base64 には / が含まれ得るため。
  sed -i "s|^JWT_SECRET=.*|JWT_SECRET=${secret}|" .env
  log ".env を作成し、JWT_SECRET を自動生成しました"
fi

# -----------------------------------------------------------------------------
# 2. main への push を防ぐ git hook を有効化する
#
# 無料プランではブランチ保護が使えないため hook で代替している。
# 従来は README で受講者に実行してもらっていたが、実行しなければ効かなかった。
# コンテナ側で必ず設定されるようにする。
# -----------------------------------------------------------------------------
if [[ -d .githooks ]]; then
  git config core.hooksPath .githooks
  log "main への push を防ぐ hook を有効化しました"
else
  warn ".githooks が見つかりません"
fi

# 実行ビットは git に記録済み（100755）だが、環境によっては落ちることがあるため念のため。
# Windows のバインドマウント上では chmod 自体ができないので、失敗しても無視する。
if [[ -f .githooks/pre-push && ! -x .githooks/pre-push ]]; then
  chmod +x .githooks/pre-push 2>/dev/null || warn "hook に実行権限を付けられませんでした"
fi

# -----------------------------------------------------------------------------
# 3. 依存パッケージをインストールする
# -----------------------------------------------------------------------------
log "依存パッケージをインストールしています（初回は数分かかります）"
npm ci

# -----------------------------------------------------------------------------
# 完了
# -----------------------------------------------------------------------------
cat <<'MSG'

  セットアップが完了しました。

    npm run dev     開発サーバーを起動（http://localhost:3000）
    npm test        テストを実行
    npm run build   ビルド（型エラーはここで分かる）

  まずは .docs/curriculum/00_basic_design.md を読んでください。

MSG
